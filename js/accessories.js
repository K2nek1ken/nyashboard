import { paletteColor, lighten } from "./palette.js";

// Украшения вокруг аватарки. Рисуются отдельным слоем поверх картинки, но ПОД
// эмодзи-статусом, чтобы статус оставался читаемым.
//
// Координаты в системе 100×100, где аватарка занимает центральный круг
// радиусом 50. Слой чуть шире картинки и не обрезается, поэтому элементы
// могут заходить за её край.
//
// Цвет задаётся владельцем профиля из общей палитры и не зависит от того,
// какой акцент выбрал смотрящий: украшение должно выглядеть одинаково у всех.
// Наборы разделены: у профилей и каналов свои украшения, и смешивать их
// не стоит — принадлежность к каналу должна читаться с первого взгляда.
// Пометка forChannel означает «только для каналов», её отсутствие — «только
// для людей». Вариант «без украшений» доступен и там, и там.
const ITEMS = {
  none: { label: "Без украшений", forChannel: true, forUser: true, svg: () => "" },

  // Четырёхконечная звезда в левом верхнем углу — знак канала.
  spark: {
    label: "Искра",
    forChannel: true,
    svg: (c) => {
      const p = (x, y, long, short) =>
        `${x},${y - long} ${x + short},${y - short} ${x + long},${y} ` +
        `${x + short},${y + short} ${x},${y + long} ${x - short},${y + short} ` +
        `${x - long},${y} ${x - short},${y - short}`;
      return `<polygon points="${p(20, 22, 15, 4.2)}" fill="${c}"/>`;
    }
  },

  // Ободок с ушками: дуга по верхней части аватарки плюс два треугольника.
  // Именно ободок, а не приставленные ушки — так он выглядит как надетая вещь.
  // Ободок с ушками. Разбор эскиза:
  //   • сама дуга лежит ВНУТРИ круга аватарки, а не поверх её края —
  //     получается надетый ободок, а не кольцо вокруг;
  //   • ушки — четырёхугольники (не треугольники), стоят на концах дуги
  //     и торчат наружу вверх, не залезая на лицо.
  // Дуга строится как разность двух окружностей почти одного радиуса,
  // поэтому она тонкая и повторяет изгиб аватарки.
  ears: {
    label: "Ушки",
    svg: (c) => `
      <path d="M14,44 A38,38 0 0 1 86,44" fill="none" stroke="${c}"
            stroke-width="3" stroke-linecap="round"/>
      <polygon points="15.5,41 12,3 34,17 30,33" fill="${c}"/>
      <polygon points="84.5,41 88,3 66,17 70,33" fill="${c}"/>`
  },

  // Цветок сбоку: шесть овальных лепестков и более яркая сердцевина.
  flower: {
    label: "Цветочек",
    svg: (c) => {
      const core = lighten(c, 0.45);
      const petals = [0, 60, 120, 180, 240, 300].map(a =>
        `<ellipse cx="0" cy="-9.5" rx="6" ry="9.5" fill="${c}" transform="rotate(${a})"/>`
      ).join("");
      // Слева, а не справа: правый верхний угол занят эмодзи-статусом,
      // и там они перекрывали друг друга.
      return `<g transform="translate(19,30)">${petals}<circle cx="0" cy="0" r="5.2" fill="${core}"/></g>`;
    }
  },

  halo: {
    label: "Нимб",
    svg: (c) => `
      <ellipse cx="50" cy="14" rx="26" ry="7.5" fill="none"
               stroke="${c}" stroke-width="4.5"/>`
  },

  // Кольцо переменной толщины: по бокам шире, сверху и снизу уже — так оно
  // читается как круг, лежащий под наклоном, а не как ровная обводка.
  // Собирается из двух эллипсов с правилом «чётности»: внутренний вырезает
  // середину, и обводить его отдельно не нужно.
  // Нимб-серафим по эскизу Неко: три вытянутых кольца под углами и круг
  // в середине. Углы ±17.5° взяты из самого эскиза.
  halo2: {
    label: "Нимб серафима",
    forChannel: true,
    svg: (c) => {
      // Три кольца под углом, как на эскизе, но над аватаркой, а не поверх
      // неё: в полный размер они накрывали лицо и читались как решётка.
      const ring = (angle) =>
        `<ellipse cx="50" cy="13" rx="30" ry="9" fill="none"
                  stroke="${c}" stroke-width="2.4"
                  transform="rotate(${angle} 50 13)"/>`;
      return `${ring(0)}${ring(16)}${ring(-16)}
              <circle cx="50" cy="13" r="4.6" fill="${c}"/>`;
    }
  },

  // Пятиконечная звезда сбоку — как цветочек, но для каналов.
  star: {
    label: "Звёздочка",
    forChannel: true,
    svg: (c) => {
      // Внешний радиус больше, чем у искры: у пятиконечной звезды между
      // лучами много пустоты, и при равной ширине она кажется вдвое мельче.
      // Внутренний тоже подтянут — так лучи шире и звезда читается плотнее.
      const pts = [];
      for (let i = 0; i < 10; i++) {
        const r = i % 2 === 0 ? 14.5 : 6.4;
        const a = (Math.PI / 5) * i - Math.PI / 2;
        // Центр там же, где был: звезда должна лежать на краю аватарки
        // внахлёст, а не висеть рядом с ней.
        pts.push(`${(19 + Math.cos(a) * r).toFixed(1)},${(28 + Math.sin(a) * r).toFixed(1)}`);
      }
      return `<polygon points="${pts.join(" ")}" fill="${c}"/>`;
    }
  }
};

// Для людей — всё, что не помечено как «только для каналов».
export const ACCESSORIES = Object.fromEntries(
  Object.entries(ITEMS)
    .filter(([, v]) => !v.forChannel || v.forUser)
    .map(([k, v]) => [k, v.label])
);

// Для каналов — только помеченные.
export const CHANNEL_ACCESSORIES = Object.fromEntries(
  Object.entries(ITEMS)
    .filter(([, v]) => v.forChannel)
    .map(([k, v]) => [k, v.label])
);

// Украшение поверх аватарки. Параметр preview — для кнопок выбора:
// там оно должно вписаться в кнопку, а не разложиться вокруг аватарки.
export function accessoryHtml(key, colorKey, preview = false) {
  const item = ITEMS[key];
  if (!item || key === "none") return "";
  const svg = item.svg(paletteColor(colorKey));
  if (!svg) return "";

  // Размеры вписаны прямо в разметку: если стиль почему-то не применился,
  // элемент со стороной ноль просто не был бы виден, и причину искать долго.
  // Из-за этого же они сильнее любого правила снаружи — поэтому для кнопок
  // выбора подставляем свои, а не пытаемся перебить их со стороны.
  const box = preview
    ? "position:absolute;inset:10%;width:80%;height:80%;"
    : "position:absolute;inset:-18%;width:136%;height:136%;";

  return `<svg class="avatar-accessory${preview ? " accessory-preview" : ""}"
    viewBox="0 0 100 100" aria-hidden="true"
    style="${box}pointer-events:none;z-index:1;overflow:visible;"
  >${svg}</svg>`;
}
