window.addEventListener("DOMContentLoaded", async () => {
  const { initRouter } = await import("./router.js");

  // Сбой вкладки не должен ронять всё остальное. Раньше ошибка здесь
  // прерывала загрузку целиком: роутер не запускался, обработчики входа
  // не навешивались — и человек не мог даже войти в аккаунт, пока
  // не уходил на другую вкладку.
  try {
    await initPage();
  } catch (e) {
    console.error("Вкладка не запустилась:", e);
    const { showPageError } = await import("./page-error.js");
    showPageError(e);
  }

  initRouter({ initPage, destroyPage });
});


// ============================================================
//  Отметка «обновилось»
//
//  Возможностей много, и появляются они постоянно. Без отметки о новых
//  узнаёшь случайно — или не узнаёшь вовсе.
//
//  Считаем отпечаток списка: если он изменился с прошлого захода,
//  значит что-то дописали. Сравниваем сам текст, а не количество:
//  правка формулировки — тоже повод заглянуть.
// ============================================================

export function aboutFingerprint() {
  const all = SECTIONS.flatMap(s => [s.title, ...s.items]).join("|");

  // Короткая свёртка: хранить весь текст ради сравнения незачем.
  let hash = 0;
  for (let i = 0; i < all.length; i++) {
    hash = (hash * 31 + all.charCodeAt(i)) | 0;
  }
  return String(hash);
}

// Изменилось ли что-то с тех пор, как человек сюда заходил.
export function aboutHasNews() {
  try {
    return localStorage.getItem("nyash_about_seen") !== aboutFingerprint();
  } catch {
    return false;
  }
}

// Запоминаем, что прочитано.
export function markAboutSeen() {
  try { localStorage.setItem("nyash_about_seen", aboutFingerprint()); } catch {}
}
