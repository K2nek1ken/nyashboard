function render() {
  document.getElementById("aboutList").innerHTML = SECTIONS.map(s => `
    <div class="about-card">
      <div class="about-card-title"><span class="nf">${s.icon}</span> ${s.title}</div>
      <ul>${s.items.map(i => `<li>${i}</li>`).join("")}</ul>
    </div>`).join("");
}

