// ============================================================
//  Запуск и сворачивание вкладки
//
//  Переход между вкладками не перезагружает страницу (см. router.js),
//  поэтому содержимое нужно уметь и включать, и выключать: живые подписки
//  на базу обязаны закрываться, иначе с каждым переходом их копилось бы
//  всё больше.
// ============================================================
export async function initPage() {
  // Человек открыл вкладку — значит новое он увидел. Отмечаем не сразу,
  // а через пару секунд: пролистнуть мимо не считается прочтением.
  setTimeout(() => {
    markAboutSeen();
    import("./notifications.js").then(n => n.paintTabDots?.()).catch(() => {});
  }, 2000);

  keepScrollPosition();
  render();

  document.getElementById("hideAboutBtn")?.addEventListener("click", () => {
    setSetting("showAbout", "off");
    showToast("Вкладка скрыта — вернуть можно в настройках");
    setTimeout(() => { goTo("index.html"); }, 900);
  });
}

export function destroyPage() {
  stopPage?.();
}

