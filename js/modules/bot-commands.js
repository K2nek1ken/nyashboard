//  Простейшая, с целью (в ответ на чьё-то сообщение):
//
//      { cmd: ["обнять", "обними"], to: "обнял|обняла" }
//
//    получится: «неко обнял кого-то»
//    Слева от «|» мужская форма, справа женская. Для гостей без пола
//    покажется «обнял(а)» — движок соберёт сам.
//
//  Со своим текстом, если шаблона мало:
//
//      { cmd: ["кусь"], to: (a, b) => `${a} делает ${b} кусь!` }
//
//  Нужно склонение внутри своего текста — оно приходит четвёртым:
//
//      { cmd: ["дать"], rest: true,
//        to: (a, b, what, past) => `${a} ${past("дал", "дала")} ${b} ${what}` }
//
//    a — кто вызвал, b — кому адресовано.
//
//  Без цели (работает сама по себе):
//
//      { cmd: ["мяу"], self: "мяукнул|мяукнула" }
//
//  С продолжением — всё, что после команды, попадает в текст:
//
//      { cmd: ["дать"], rest: true, to: (a, b, what) => `${a} дал ${b} ${what}` }
//
//    «дать леща» → «неко дал кому-то леща»
//
//  Хвост после действия — когда нужно дописать что-то в конце:
//
//      { cmd: ["обнять"], to: "обнял|обняла", tail: "♡" }
//
//  ---- что нельзя ----
//
//  Команда не может обращаться к базе или сети: такие случаи
//  (кошелёк, казино) живут в casino.js и подключены отдельно.
// ============================================================

