// Версия сборки. Показывается внизу настроек.
//
// С первого выпуска — обычная нумерация с кодовым именем вместо даты:
// дата говорит только «когда», а имя запоминается и отличает выпуски
// друг от друга.
export const BUILD = {
  version: "1.0.0",
  codename: "Сайя",
  date: "2026-09-13"
};

// Строка для показа: «версия 1.0.0 — Сайя»
export function buildLabel() {
  return `версия ${BUILD.version} — ${BUILD.codename}`;
}
