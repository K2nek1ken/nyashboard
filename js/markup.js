// ============================================================
//  Разметка текста в записях и сообщениях
//
//    **жирный**      __курсив__      `моноширинный`
//    ### заголовок   {16}размер текста{17}другой размер
//
//  Про размер: первое число открывает, следующее — закрывает предыдущее и
//  сразу открывает новое. То есть «{16}раз{17}два» — это «раз» шестнадцатым,
//  «два» семнадцатым, ровно как описал Неко.
//
//  Число должно быть целым и меньше 26 — иначе текст в ленте можно было бы
//  растянуть на весь экран. Если правило не выполнено, скобки остаются
//  обычным текстом: это не ошибка, просто не разметка.
//
//  Применяется ПОСЛЕ экранирования, поэтому в разметку не может попасть
//  чужой HTML.
// ============================================================

const MAX_SIZE = 26;

export function applyMarkup(escapedText) {
  let out = escapedText;

  // заголовок: строка, начинающаяся с ###
  out = out.replace(/^###\s*(.+)$/gm, '<span class="md-head">$1</span>');

  // моноширинный — первым, чтобы внутри него ничего больше не разбиралось
  out = out.replace(/`([^`\n]+)`/g, '<code class="md-code">$1</code>');

  out = out.replace(/\*\*([^*\n]+)\*\*/g, "<b>$1</b>");
  out = out.replace(/__([^_\n]+)__/g, "<i>$1</i>");

  out = applySizes(out);
  return out;
}

// Размеры разбираются отдельно: это не пара «открыть/закрыть», а переключатель,
// поэтому обычной заменой по образцу не обойтись.
function applySizes(text) {
  const parts = text.split(/(\{\d{1,2}\})/g);
  let open = false;
  let result = "";

  for (const part of parts) {
    const m = /^\{(\d{1,2})\}$/.exec(part);
    if (!m) { result += part; continue; }

    const size = Number(m[1]);
    if (!Number.isInteger(size) || size < 1 || size >= MAX_SIZE) {
      result += part;           // не подходит под правило — оставляем как текст
      continue;
    }
    if (open) result += "</span>";
    result += `<span class="md-size" style="font-size:${size}px">`;
    open = true;
  }
  if (open) result += "</span>";
  return result;
}
